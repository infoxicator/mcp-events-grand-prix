import {expect,test} from '@playwright/test';

test('historical race picker plays recorded telemetry and switches 2D and 3D views',async({page})=>{
 const errors:string[]=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/?replay=9590&view=telemetry');
 await expect(page.getByRole('heading',{name:'2024 Italian Grand Prix'})).toBeVisible();
 const map=page.getByRole('img',{name:'2D track map of recorded race positions'});
 await expect(map).toBeVisible();
 const grid=await map.evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL());
 await expect(page.locator('#replay-standings tr')).toHaveCount(20);
 await expect(page.getByText('Charles Leclerc · Ferrari')).toBeVisible();
 await page.getByLabel('Go to lap').selectOption('16');
 await expect(page.locator('#replay-lap')).toHaveText('Lap 16 / 53');
 expect(await map.evaluate(canvas=>(canvas as HTMLCanvasElement).toDataURL())).not.toBe(grid);
 await expect(page.locator('#replay-driver-speed')).toHaveText(/\d+ km\/h/);
 await page.getByRole('button',{name:'Lando Norris',exact:true}).click();
 await expect(page.getByText('Lando Norris · McLaren')).toBeVisible();
 await page.getByLabel('Playback speed').selectOption('64');
 await page.getByRole('button',{name:'Play',exact:true}).click();
 const start=await page.locator('#replay-elapsed').textContent();
 await expect(page.locator('#replay-elapsed')).not.toHaveText(start!);
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByRole('button',{name:'3D track',exact:true}).click();
 await expect(page.getByRole('button',{name:'3D track',exact:true})).toHaveAttribute('aria-pressed','true');
 const scene=page.getByRole('img',{name:'3D view of recorded race positions'});
 await expect(scene).toBeVisible();
 await expect.poll(()=>scene.evaluate(canvas=>(canvas as HTMLCanvasElement).width)).toBeGreaterThan(300);
 await page.getByRole('button',{name:'2D telemetry'}).click();
 await expect(page.getByRole('img',{name:'3D view of recorded race positions'})).toHaveCount(0);
 await page.getByLabel('Race',{exact:true}).selectOption('9558');
 await expect(page.getByRole('heading',{name:'2024 British Grand Prix'})).toBeVisible();
 await expect(page.getByText('Lewis Hamilton · Mercedes')).toBeVisible();
 await page.getByLabel('Go to lap').selectOption('30');
 await expect(page.locator('#replay-weather')).toContainText('Rain');
 await page.getByText('Connect a model',{exact:true}).click();
 await expect(page.getByLabel('Model benchmark prompt')).toHaveValue(/race 9558, driver 44/);
 await expect(page).toHaveURL(/replay=9558&view=telemetry/);
 expect(errors).toEqual([]);
});
